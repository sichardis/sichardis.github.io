"""Build the local ES modules into a deferred classic script, including file:// use.

Run python3 build-browser.py after changing any JavaScript source module.
Only local named imports and named declaration exports are supported deliberately.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent
IMPORT = re.compile(r"^import\s+\{([^}]+)\}\s+from\s+['\"]([^'\"]+)['\"];?\s*$", re.M)
EXPORT = re.compile(r"\bexport\s+(const|let|(?:async\s+)?function)\s+(\w+)")


def build():
    modules = []
    visited = set()

    def visit(name):
        if name in visited:
            return
        visited.add(name)
        source = (ROOT / name).read_text()
        imports = list(IMPORT.finditer(source))
        for match in imports:
            path = match[2].split('?')[0]
            if not path.startswith('./') or '/' in path[2:]:
                raise ValueError(f'Unsupported module path: {path}')
            visit(path[2:])

        def replace_import(match):
            bindings = re.sub(r'\s+as\s+', ': ', match[1].strip())
            path = match[2].split('?')[0][2:]
            return f'const {{ {bindings} }} = __modules[{json.dumps(path)}];'

        source = IMPORT.sub(replace_import, source)
        exports = [match[2] for match in EXPORT.finditer(source)]
        source = EXPORT.sub(lambda match: f'{match[1]} {match[2]}', source)
        modules.append(f'// {name}\n__modules[{json.dumps(name)}] = (() => {{\n{source}\nreturn {{{", ".join(exports)}}};\n}})();')

    visit('script.js')
    output = '// Generated by python3 build-browser.py; edit the source modules.\n(() => {\n"use strict";\nconst __modules = Object.create(null);\n'
    output += '\n\n'.join(modules) + '\n})();\n'
    (ROOT / 'app.js').write_text(output)
    print(f'Built app.js from {len(modules)} modules.')


if __name__ == '__main__':
    build()
