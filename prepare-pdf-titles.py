"""Generate tiny incremental PDF title updates without rewriting the original pages.

Run with the bundled Python environment (pypdf) after replacing a source PDF.
The browser appends these updates to both ordinary PDFs and multipart PDFs.
"""
from base64 import b64encode
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import json
import logging

from pypdf import PdfReader, PdfWriter
from pypdf.generic import BooleanObject, DictionaryObject, NameObject

ROOT = Path(__file__).resolve().parent
PROJECT_NAMES = {
    "chak": "착!(Chak!)",
    "bridge": "브릿지(Bridge)",
    "korail": "코레일톡",
    "bluedog": "블루독(Blue Dog)",
    "rocketfresh": "쿠팡 로켓프레시",
    "kaywon": "계원예술대학교",
}
DIRECT_SOURCES = {
    "chak": "assets/chak-plan.pdf",
    "bridge": "assets/bridge.pdf",
    "korail": "assets/korail.pdf",
    "bluedog": "assets/bluedog.pdf",
    "kaywon": "assets/kaywon-proposal.pdf",
}


def load_sources():
    source = (ROOT / "case-studies.js").read_text()
    cases = json.loads(source[source.index("{"):].strip().removesuffix(";"))
    for project_id in [*PROJECT_NAMES, "chak-storyboard", "bluedog-storyboard", "rocketfresh-storyboard", "kaywon-storyboard"]:
        case = cases[project_id]
        parts = case.get("pdfParts")
        if parts:
            paths = [f"{parts['folder'].removeprefix('./')}/{i:02}.bin" for i in range(1, parts["count"] + 1)]
        else:
            paths = [case.get("pdf", DIRECT_SOURCES.get(project_id)).removeprefix("./")]
        yield project_id, paths


def build():
    documents = {}
    # pypdf can warn when an incremental root replaces the original cached root.
    # Every generated document is reparsed and checked below.
    logging.getLogger("pypdf").setLevel(logging.ERROR)
    for project_id, sources in load_sources():
        original = b"".join((ROOT / path).read_bytes() for path in sources)
        name = PROJECT_NAMES[project_id.removesuffix("-storyboard")]
        filename = f"{name}_정서영.pdf"
        reader = PdfReader(BytesIO(original))
        writer = PdfWriter(BytesIO(original), incremental=True)
        writer.add_metadata({"/Title": filename})
        old_preferences = writer.root_object.get("/ViewerPreferences")
        preferences = DictionaryObject(old_preferences.get_object() if old_preferences else {})
        preferences[NameObject("/DisplayDocTitle")] = BooleanObject(True)
        writer.root_object[NameObject("/ViewerPreferences")] = preferences
        output = BytesIO()
        writer.write(output)
        updated = output.getvalue()
        if not updated.startswith(original):
            raise ValueError(f"Original PDF bytes changed: {project_id}")
        checked = PdfReader(BytesIO(updated))
        assert checked.metadata.title == filename
        assert checked.viewer_preferences.display_doctitle
        assert len(checked.pages) == len(reader.pages)
        for before, after in zip(reader.pages, checked.pages):
            assert before.mediabox == after.mediabox
            assert before.get_contents().get_data() == after.get_contents().get_data()
        documents[project_id] = {
            "filename": filename,
            "sourceSize": len(original),
            "sourceSha256": sha256(original).hexdigest(),
            "append": b64encode(updated[len(original):]).decode("ascii"),
        }
        print(f"{project_id}: {len(checked.pages)} pages, {len(updated) - len(original)} byte title update")
    (ROOT / "pdf-documents.js").write_text(
        "// Generated by prepare-pdf-titles.py. Original page data is preserved.\n"
        + "export const pdfDocuments = "
        + json.dumps(documents, ensure_ascii=False, indent=2)
        + ";\n"
    )


if __name__ == "__main__":
    build()
